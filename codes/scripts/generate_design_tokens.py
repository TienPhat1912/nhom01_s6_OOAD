"""Generate Web and WinForms tokens from the shared design source. No dependencies."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
tokens = json.loads((root / "design/tokens.json").read_text(encoding="utf-8"))
css = ["/* Generated by scripts/generate_design_tokens.py. */", ":root {"]
cs = ["// Generated by scripts/generate_design_tokens.py.", "namespace Hospital.Desktop.Design;", "", "public static class DesignTokens", "{"]
for name, value in tokens["colors"].items():
    css.append(f"  --color-{name}: {value};")
    member = "".join(part.capitalize() for part in name.split("-"))
    cs.append(f'    public static readonly Color {member} = ColorTranslator.FromHtml("{value}");')
for group, prefix in [("spacing", "space"), ("radius", "radius"), ("fontSizes", "font")]:
    for name, value in tokens[group].items():
        css.append(f"  --{prefix}-{name}: {value}px;")
        cs.append(f"    public const int {prefix.capitalize()}{name.capitalize()} = {value};")
css += ["}", ""]
cs += ["}", ""]
outputs = {
    root / "src/Hospital.Web/wwwroot/css/tokens.css": "\n".join(css),
    root / "src/Hospital.Desktop/Design/DesignTokens.g.cs": "\n".join(cs)
}
for path, content in outputs.items():
    if "--check" in sys.argv:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit(f"Tokens out of date: {path}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
print("Design tokens are synchronized.")
